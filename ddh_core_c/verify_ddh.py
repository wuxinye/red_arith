from math import gcd

SCALE = 10**8

def lcm(a, b):
    return a // gcd(a, b) * b

# ============ 加法 ============
def add(m1, k1, d1, m2, k2, d2):
    m = m1 + m2
    k = k1 + k2
    d = lcm(d1, d2)
    carry = k // d
    return m + carry, k % d, d

# ============ 减法 ============
def sub(m1, k1, d1, m2, k2, d2):
    m = m1 - m2
    k = k1 - k2
    d = lcm(d1, d2)
    if k < 0:
        k += d
        m -= 1
    return m, k, d

# ============ 乘法（修正公式）============
def mul(m1, k1, d1, m2, k2, d2):
    A1 = m1 * d1 + k1
    A2 = m2 * d2 + k2
    total_A = A1 * A2 // SCALE
    Dnew = d1 * d2
    return total_A // Dnew, total_A % Dnew, Dnew

# ============ 除法 ============
def div(m1, k1, d1, m2, k2, d2):
    A1 = m1 * d1 + k1
    A2 = m2 * d2 + k2
    if A2 == 0: raise ZeroDivisionError
    total_A = A1 * d2 * SCALE
    Dnew = d1 * A2
    return total_A // Dnew, total_A % Dnew, Dnew

# ============ 真实值 ============
def real(m, k, d):
    return (m + k / d) / SCALE

def fmt(m, k, d):
    return f"{m//SCALE}.{m%SCALE:08d} + {k} + {d}"

