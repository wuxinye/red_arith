"""
DDH 精确验证（简化版）
验证 C 代码逻辑的正确性
"""
from math import gcd

SCALE = 10**8

def lcm(a, b):
    return a // gcd(a, b) * b

def add(m1, k1, d1, m2, k2, d2):
    m = m1 + m2
    k = k1 + k2
    d = lcm(d1, d2)
    return m + k // d, k % d, d

def mul(m1, k1, d1, m2, k2, d2):
    A1 = m1 * d1 + k1
    A2 = m2 * d2 + k2
    tA = A1 * A2 // SCALE
    tD = d1 * d2
    return tA // tD, tA % tD, tD

def sub(m1, k1, d1, m2, k2, d2):
    m = m1 - m2
    k = k1 - k2
    d = lcm(d1, d2)
    if k < 0:
        k += d
        m -= 1
    return m, k, d

def div(m1, k1, d1, m2, k2, d2):
    A1 = m1 * d1 + k1
    A2 = m2 * d2 + k2
    tA = A1 * d2 * SCALE
    tD = d1 * A2
    return tA // tD, tA % tD, tD

def real(m, k, d):
    return (m + k / d) / SCALE

def fmt(m, k, d):
    return f"{m//SCALE}.{m%SCALE:08d} + {k} + {d}"

